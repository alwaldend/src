func (d *delivery) readIgnoredText(
	ctx context.Context,
	inputPath string,
	flag string,
	description string,
) (string, error) {
	if strings.TrimSpace(inputPath) == "" {
		return "", fmt.Errorf("%s is required", flag)
	}
	if filepath.IsAbs(inputPath) {
		if filepath.Clean(inputPath) != inputPath {
			return "", fmt.Errorf(
				"%s path must use a canonical lexical form",
				description,
			)
		}
	} else if err := validateTaskOutputPath(
		filepath.ToSlash(inputPath),
	); err != nil {
		return "", fmt.Errorf(
			"%s must be under an ignored out/<task>/ directory: %w",
			description,
			err,
		)
	}
	absolute := inputPath
	if !filepath.IsAbs(absolute) {
		absolute = filepath.Join(d.repository.directory, absolute)
	}
	absolute = filepath.Clean(absolute)
	resolved, err := filepath.EvalSymlinks(absolute)
	if err != nil {
		return "", fmt.Errorf("resolve %s symlinks: %w", description, err)
	}
	if filepath.Clean(resolved) != filepath.Clean(absolute) {
		return "", fmt.Errorf("%s path must not contain symlinks", description)
	}
	relative, err := filepath.Rel(d.repository.directory, resolved)
	if err != nil {
		return "", fmt.Errorf("locate %s in repository: %w", description, err)
	}
	relative = filepath.ToSlash(relative)
	if err := validateTaskOutputPath(relative); err != nil {
		return "", fmt.Errorf(
			"%s must be under the repository's ignored out/<task>/ directory: %w",
			description,
			err,
		)
	}
	tracked, err := d.repository.pathTracked(ctx, relative)
	if err != nil {
		return "", err
	}
	if tracked {
		return "", fmt.Errorf("%s must be untracked", description)
	}
	ignored, err := d.repository.pathIgnored(ctx, relative)
	if err != nil {
		return "", err
	}
	if !ignored {
		return "", fmt.Errorf("%s must be ignored by Git", description)
	}
	before, err := os.Lstat(resolved)
	if err != nil {
		return "", fmt.Errorf("inspect %s: %w", description, err)
	}
	if !before.Mode().IsRegular() {
		return "", fmt.Errorf("%s must be a regular non-symlink file", description)
	}
	if before.Size() > commitMessageLimit {
		return "", fmt.Errorf("%s exceeds 60 KiB", description)
	}
	file, err := os.Open(resolved)
	if err != nil {
		return "", fmt.Errorf("open %s: %w", description, err)
	}
	defer file.Close()
	after, err := file.Stat()
	if err != nil {
		return "", fmt.Errorf("inspect opened %s: %w", description, err)
	}
	if !after.Mode().IsRegular() || !os.SameFile(before, after) {
		return "", fmt.Errorf("%s changed while it was being opened", description)
	}
	contents, err := io.ReadAll(io.LimitReader(file, commitMessageLimit+1))
	if err != nil {
		return "", fmt.Errorf("read %s: %w", description, err)
	}
	if len(contents) > commitMessageLimit {
		return "", fmt.Errorf("%s exceeds 60 KiB", description)
	}
	readAfter, err := file.Stat()
	if err != nil {
		return "", fmt.Errorf("inspect read %s: %w", description, err)
	}
	if _, err := file.Seek(0, io.SeekStart); err != nil {
		return "", fmt.Errorf("rewind %s: %w", description, err)
	}
	confirmed, err := io.ReadAll(io.LimitReader(file, commitMessageLimit+1))
	if err != nil {
		return "", fmt.Errorf("reread %s: %w", description, err)
	}
	finalInfo, err := file.Stat()
	if err != nil {
		return "", fmt.Errorf("inspect reread %s: %w", description, err)
	}
	pathAfter, err := os.Lstat(resolved)
	if err != nil {
		return "", fmt.Errorf("reinspect %s path: %w", description, err)
	}
	if !bytes.Equal(contents, confirmed) || !os.SameFile(before, pathAfter) ||
		!os.SameFile(after, readAfter) || !os.SameFile(readAfter, finalInfo) ||
		after.Size() != readAfter.Size() || readAfter.Size() != finalInfo.Size() ||
		!after.ModTime().Equal(readAfter.ModTime()) ||
		!readAfter.ModTime().Equal(finalInfo.ModTime()) {
		return "", fmt.Errorf("%s changed while it was being read", description)
	}
	return string(contents), nil
}

type publishOptions struct {
	ValidatedHead string
	ReceiptFile   string
}

type publishReport struct {
	Status        string              `json:"status"`
	HeadOID       string              `json:"head_oid"`
	TreeOID       string              `json:"tree_oid"`
	RemoteHeadOID string              `json:"remote_head_oid"`
	PullRequest   *pullRequest        `json:"pull_request"`
	Verified      bool                `json:"verified"`
	Receipt       *preparationReceipt `json:"receipt,omitempty"`
}

type revalidationRequiredError struct {
	Report *publishReport
}

func (e *revalidationRequiredError) Error() string {
	return fmt.Sprintf(
		"publish paused before push because HEAD changed; rerun validations and retry with --validated-head=%s",
		e.Report.HeadOID,
	)
}

func (d *delivery) publish(
	ctx context.Context,
	options publishOptions,
) (result *publishReport, returnErr error) {
	if !isObjectID(options.ValidatedHead) {
		return nil, fmt.Errorf("--validated-head must be a full Git object ID")
	}
	receiptTransaction, err := d.beginReceiptTransaction(
		ctx,
		options.ReceiptFile,
		true,
	)
	if err != nil {
		return nil, err
	}
	defer func() {
		if closeErr := receiptTransaction.close(); closeErr != nil {
			returnErr = errors.Join(returnErr, closeErr)
		}
	}()
	receipt, err := receiptTransaction.read()
	if err != nil {
		return nil, err
	}
	report, err := d.inspect(ctx)
	if err != nil {
		return nil, err
	}
	if err := d.validateReceiptContext(ctx, receipt, report); err != nil {
		return nil, fmt.Errorf("preparation receipt refused: %w", err)
	}
	if report.BaseOID != receipt.BaseOID {
		descendant, err := d.repository.isAncestor(
			ctx,
			receipt.BaseOID,
			report.BaseOID,
		)
		if err != nil {
			return nil, err
		}
		if !descendant {
			return nil, fmt.Errorf(
				"fetched base is not a descendant of the preparation receipt base",
			)
		}
	}
	if err := ensureNoRefusals(report); err != nil {
		return nil, err
	}
	if options.ValidatedHead != receipt.PreparedHeadOID {
		return nil, fmt.Errorf(
			"validated HEAD differs from the preparation receipt head",
		)
	}
	if len(report.Status.Staged) != 0 {
		return nil, fmt.Errorf("publication requires a clean index")
	}
	if err := requireCleanPreparedScope(report.Status, receipt.Scope); err != nil {
		return nil, err
	}
	if err := d.repository.requireDefaultIndexFlags(
		ctx,
		receipt.Scope.AuthorizedPaths,
	); err != nil {
		return nil, fmt.Errorf("publication index flag gate: %w", err)
	}
	if err := d.repository.requireIndexTree(
		ctx,
		receipt.PreparedTreeOID,
	); err != nil {
		return nil, fmt.Errorf("publication index gate: %w", err)
	}
	if report.NeedsRebase && !report.Status.clean() {
		return nil, fmt.Errorf(
			"publication requires a clean worktree and index before rebase",
		)
	}
	if report.UniqueCommitCount != 1 || len(report.MergeCommits) != 0 {
		return nil, fmt.Errorf("publication requires exactly one non-merge feature commit")
	}
	if report.LocalHeadOID != options.ValidatedHead {
		return nil, fmt.Errorf(
			"validated HEAD %s differs from current HEAD %s",
			options.ValidatedHead,
			report.LocalHeadOID,
		)
	}
	body, err := d.repository.commitBody(ctx, report.LocalHeadOID)
	if err != nil {
		return nil, err
	}
	if !hasFinalLine(body, commitDisclaimer) {
		return nil, fmt.Errorf("feature commit lacks the required commit disclaimer")
	}
	projection, err := d.repository.projection(ctx, report.LocalHeadOID)
	if err != nil {
		return nil, err
	}
	if !receiptAllowsRemoteHead(receipt, report.RemoteHeadOID) {
		return nil, fmt.Errorf(
			"fetched remote head differs from the preparation receipt lease",
		)
	}
	pullRequestState, err := receipt.pullRequestState(
		report.PullRequest,
		report.RemoteHeadOID,
		projection,
	)
	if err != nil {
		return nil, err
	}
	if pullRequestState == receiptPullRequestCreatedDesired {
		receipt, err = receipt.bindCreatedPullRequest(
			report.PullRequest,
			report.RemoteHeadOID,
			projection,
		)
		if err != nil {
			return nil, err
		}
		if err := receiptTransaction.write(ctx, receipt); err != nil {
			return nil, err
		}
	}

	snapshot, err := d.repository.snapshot(
		ctx,
		d.fetchEndpoint,
		report.Base,
		report.Branch,
	)
	if err != nil {
		return nil, err
	}
	snapshotClosed := false
	defer func() {
		if snapshotClosed {
			return
		}
		if cleanupErr := snapshot.close(
			context.Background(),
		); cleanupErr != nil {
			returnErr = errors.Join(
				returnErr,
				fmt.Errorf("clean publication snapshot: %w", cleanupErr),
			)
		}
	}()
	if snapshot.RemoteHeadOID != report.RemoteHeadOID ||
		!receiptAllowsRemoteHead(receipt, snapshot.RemoteHeadOID) {
		return nil, fmt.Errorf("remote feature ref changed after inspection; retry from inspect")
	}
	baseAdvanced := snapshot.BaseOID != receipt.BaseOID
	if baseAdvanced {
		descendant, err := d.repository.isAncestor(
			ctx,
			receipt.BaseOID,
			snapshot.BaseOID,
		)
		if err != nil {
			return nil, err
		}
		if !descendant {
			return nil, fmt.Errorf(
				"fetched base is not a descendant of the preparation receipt base",
			)
		}
	}
	baseIsAncestor, err := d.repository.isAncestor(
		ctx,
		snapshot.BaseOID,
		report.LocalHeadOID,
	)
	if err != nil {
		return nil, err
	}
	candidateHead := report.LocalHeadOID
	rebasedScope := receipt.Scope
	if !baseIsAncestor {
		if !baseAdvanced {
			return nil, fmt.Errorf(
				"prepared head is not based on its exact receipt base",
			)
		}
		status, err := d.repository.status(ctx)
		if err != nil {
			return nil, err
		}
		if !status.clean() {
			return nil, fmt.Errorf(
				"the freshly fetched base requires a rebase, but the worktree is not clean",
			)
		}
		candidateHead, err = d.repository.rebase(
			ctx,
			snapshot.BaseOID,
			report.Branch,
			report.LocalHeadOID,
			func(
				checkContext context.Context,
				candidateRepository *gitRepository,
				candidateHead string,
			) error {
				var reconcileErr error
				rebasedScope, reconcileErr = reconcileRebasedAggregateScope(
					checkContext,
					candidateRepository,
					snapshot.BaseOID,
					candidateHead,
					report.LocalHeadOID,
					receipt.Scope,
				)
				return reconcileErr
			},
		)
		if err != nil {
			return nil, err
		}
		candidateTree, err := d.repository.tree(ctx, candidateHead)
		if err != nil {
			return nil, err
		}
		if err := d.repository.requireIndexTree(ctx, candidateTree); err != nil {
			return nil, fmt.Errorf("rebased publication index gate: %w", err)
		}
		if err := d.verifyAggregateScope(
			ctx,
			snapshot.BaseOID,
			candidateHead,
			rebasedScope,
		); err != nil {
			return nil, fmt.Errorf("verify rebased aggregate scope: %w", err)
		}
		derived, err := d.newPreparationReceiptWithExpectation(
			ctx,
			report.Base,
			snapshot.BaseOID,
			report.Branch,
			candidateHead,
			candidateTree,
			snapshot.RemoteHeadOID,
			receipt.ExpectedPullRequest,
			rebasedScope,
		)
		if err != nil {
			return nil, err
		}
		if err := receiptTransaction.write(ctx, derived); err != nil {
			return nil, err
		}
		revalidationReport := &publishReport{
			Status:        "revalidation_required",
			HeadOID:       candidateHead,
			TreeOID:       candidateTree,
			RemoteHeadOID: snapshot.RemoteHeadOID,
			PullRequest:   report.PullRequest,
			Receipt:       &derived,
		}
		if cleanupErr := snapshot.close(context.Background()); cleanupErr != nil {
			snapshotClosed = true
			return revalidationReport, errors.Join(
				&revalidationRequiredError{Report: revalidationReport},
				fmt.Errorf("clean publication snapshot: %w", cleanupErr),
			)
		}
		snapshotClosed = true
		return revalidationReport, &revalidationRequiredError{
			Report: revalidationReport,
		}
	}
	currentBranch, currentHead, err := d.repository.branchHead(ctx)
	if err != nil {
		return nil, err
	}
	if currentBranch != report.Branch || currentHead != candidateHead {
		return nil, fmt.Errorf("current branch or HEAD changed before publication")
	}
	if err := d.requireSingleCommit(
		ctx,
		snapshot.BaseOID,
		currentHead,
	); err != nil {
		return nil, err
	}
	if err := d.repository.rangeDiffCheck(
		ctx,
		snapshot.BaseOID,
		currentHead,
	); err != nil {
		return nil, err
	}
	if err := d.repository.verifyRequiredSignature(ctx, currentHead); err != nil {
		return nil, err
	}
	if currentHead != options.ValidatedHead {
		return nil, fmt.Errorf("HEAD changed after receipt validation")
	}
	currentStatus, err := d.repository.status(ctx)
	if err != nil {
		return nil, err
	}
	if len(currentStatus.Staged) != 0 {
		return nil, fmt.Errorf("index changed before publication")
	}
	if err := requireCleanPreparedScope(currentStatus, receipt.Scope); err != nil {
		return nil, err
	}
	currentTree, err := d.repository.tree(ctx, currentHead)
	if err != nil {
		return nil, err
	}
	if currentTree != receipt.PreparedTreeOID {
		return nil, fmt.Errorf("prepared tree changed before publication")
	}
	if err := d.repository.requireIndexTree(ctx, currentTree); err != nil {
		return nil, fmt.Errorf("final publication index gate: %w", err)
	}
	currentBody, err := d.repository.commitBody(ctx, currentHead)
	if err != nil {
		return nil, err
	}
	if !hasFinalLine(currentBody, commitDisclaimer) {
		return nil, fmt.Errorf("validated commit lacks the required disclaimer")
	}
	if cleanupErr := snapshot.close(context.Background()); cleanupErr != nil {
		snapshotClosed = true
		return nil, fmt.Errorf("clean publication snapshot: %w", cleanupErr)
	}
	snapshotClosed = true
	currentPullRequest, err := d.currentOpenPullRequest(ctx, report.Branch)
	if err != nil {
		return nil, err
	}
	if _, err := receipt.pullRequestState(
		currentPullRequest,
		snapshot.RemoteHeadOID,
		projection,
	); err != nil {
		return nil, err
	}
	if _, err := d.requireCandidateBoundary(
		ctx,
		&receipt,
		report,
		"final publication",
	); err != nil {
		return nil, err
	}
	if err := receiptTransaction.requireCurrent(ctx); err != nil {
		return nil, fmt.Errorf(
			"pre-push preparation receipt gate: %w",
			err,
		)
	}
	if err := d.repository.push(
		ctx,
		d.pushEndpoint,
		currentHead,
		snapshot.RemoteHeadRef,
		snapshot.RemoteHeadOID,
		snapshot.RemoteBaseRef,
		snapshot.BaseOID,
	); err != nil {
		return nil, err
	}
	if err := d.repository.requireBranchHead(
		ctx,
		currentBranch,
		currentHead,
	); err != nil {
		return nil, err
	}
	input := pullRequestInput{
		BaseRefName:     report.Base,
		HeadRefName:     report.Branch,
		ExpectedHeadOID: currentHead,
		Title:           projection.Title,
		Body:            projection.Body,
	}
	pullRequest := currentPullRequest
	if pullRequest != nil {
		expected := *pullRequest
		expected.State = "OPEN"
		expected.HeadRefOID = currentHead
		pullRequest = &expected
	}
	if pullRequest == nil {
		if err := receiptTransaction.requireCurrent(ctx); err != nil {
			return nil, fmt.Errorf(
				"pre-create preparation receipt gate: %w",
				err,
			)
		}
		pullRequest, err = d.forge.CreatePullRequest(
			ctx,
			d.remoteRepository,
			input,
		)
	} else if !pullRequestMatchesInput(*pullRequest, input) {
		if err := receiptTransaction.requireCurrent(ctx); err != nil {
			return nil, fmt.Errorf(
				"pre-update preparation receipt gate: %w",
				err,
			)
		}
		pullRequest, err = d.forge.UpdatePullRequest(
			ctx,
			d.remoteRepository,
			*pullRequest,
			input,
		)
	}
	if err != nil {
		return nil, err
	}
	if pullRequest != nil && !receipt.ExpectedPullRequest.Present {
		receipt, err = receipt.bindCreatedPullRequest(
			pullRequest,
			currentHead,
			projection,
		)
		if err != nil {
			return nil, err
		}
		if err := receiptTransaction.write(ctx, receipt); err != nil {
			return nil, err
		}
	}
	if err := receiptTransaction.requireCurrent(ctx); err != nil {
		return nil, fmt.Errorf(
			"final preparation receipt gate: %w",
			err,
		)
	}
	verified, err := d.verify(ctx, &receipt)
	if err != nil {
		return nil, err
	}
	if verified.Inspection.LocalHeadOID != currentHead ||
		verified.Inspection.LocalTreeOID != currentTree ||
		verified.Inspection.RemoteHeadOID != currentHead {
		return nil, fmt.Errorf(
			"final verification did not describe the exact validated candidate",
		)
	}
	if pullRequest == nil || verified.Inspection.PullRequest == nil ||
		verified.Inspection.PullRequest.ID != pullRequest.ID {
		return nil, fmt.Errorf(
			"final verification selected a different pull request",
		)
	}
	if err := receiptTransaction.requireCurrent(ctx); err != nil {
		return nil, fmt.Errorf(
			"post-verification preparation receipt gate: %w",
			err,
		)
	}
	return &publishReport{
		Status:        "published",
		HeadOID:       verified.Inspection.LocalHeadOID,
		TreeOID:       verified.Inspection.LocalTreeOID,
		RemoteHeadOID: verified.Inspection.RemoteHeadOID,
		PullRequest:   verified.Inspection.PullRequest,
		Verified:      true,
	}, nil
}

func (d *delivery) currentPullRequestMatchingInspection(
	ctx context.Context,
	report *inspection,
) (*pullRequest, error) {
	current, err := d.currentOpenPullRequest(ctx, report.Branch)
	if err != nil {
		return nil, err
	}
	if current == nil {
		return nil, fmt.Errorf("pull request changed after inspection: it is absent")
	}
	if report.PullRequest == nil {
		return nil, fmt.Errorf("pull request appeared after inspection")
	}
	if !samePullRequestMetadata(*current, *report.PullRequest) {
		return nil, fmt.Errorf(
			"pull request metadata changed after inspection; preserve possible human edits",
		)
	}
	return current, nil
}

func (d *delivery) refreshPullRequestSafety(
	ctx context.Context,
	report *inspection,
) error {
	_, err := d.currentPullRequestMatchingInspection(ctx, report)
	return err
}

func (d *delivery) currentOpenPullRequest(
	ctx context.Context,
	branch string,
) (*pullRequest, error) {
	all, err := d.forge.PullRequests(ctx, d.remoteRepository, branch)
	if err != nil {
		return nil, err
	}
	exact, err := exactPullRequests(all, d.remoteRepository, branch)
	if err != nil {
		return nil, err
	}
	current, refusals := selectOpenPullRequest(exact)
	if len(refusals) != 0 {
		return nil, fmt.Errorf(
			"cannot select exact open pull request: %s",
			strings.Join(refusals, "; "),
		)
	}
	return current, nil
}

func samePullRequestMetadata(left, right pullRequest) bool {
	return samePullRequestIdentity(left, right) &&
		left.AuthorLogin == right.AuthorLogin &&
		left.IsDraft == right.IsDraft &&
		normalizeText(left.Title) == normalizeText(right.Title) &&
		normalizeText(left.Body) == normalizeText(right.Body)
}

func samePullRequestIdentity(left, right pullRequest) bool {
	return left.ID == right.ID &&
		left.Number == right.Number &&
		left.URL == right.URL &&
		strings.EqualFold(left.State, "OPEN") &&
		strings.EqualFold(right.State, "OPEN") &&
		left.BaseRefName == right.BaseRefName &&
		left.HeadRefName == right.HeadRefName &&
		left.HeadRefOID == right.HeadRefOID &&
		strings.EqualFold(
			left.HeadRepositoryOwner,
			right.HeadRepositoryOwner,
		) &&
		strings.EqualFold(
			left.HeadRepositoryName,
			right.HeadRepositoryName,
		) &&
		left.IsCrossRepository == right.IsCrossRepository
}

func (d *delivery) requirePullRequestProjection(
	ctx context.Context,
	report *inspection,
) error {
	if report.PullRequest == nil {
		return nil
	}
	if report.RemoteHeadOID == "" {
		return fmt.Errorf("pull request exists without a fetched remote head")
	}
	projection, err := d.repository.projection(ctx, report.RemoteHeadOID)
	if err != nil {
		return err
	}
	if !pullRequestMatchesProjection(
		*report.PullRequest,
		projection,
		report.Base,
		report.Branch,
	) {
		return fmt.Errorf(
			"pull request is not the fetched remote commit projection; preserve possible human edits",
		)
	}
	return nil
}

func pullRequestMatchesProjection(
	pullRequest pullRequest,
	projection commitProjection,
	base string,
	head string,
) bool {
	return pullRequest.BaseRefName == base &&
		pullRequest.HeadRefName == head &&
		normalizeText(pullRequest.Title) == normalizeText(projection.Title) &&
		normalizeText(pullRequest.Body) == normalizeText(projection.Body)
}

func (d *delivery) requireSingleCommit(
	ctx context.Context,
	baseOID string,
	headOID string,
) error {
	count, err := d.repository.commitCount(ctx, baseOID, headOID)
	if err != nil {
		return err
	}
	merges, err := d.repository.mergeCommits(ctx, baseOID, headOID)
	if err != nil {
		return err
	}
	if count != 1 || len(merges) != 0 {
		return fmt.Errorf(
			"prepared feature range has %d commits and %d merges; want one commit and no merges",
			count,
			len(merges),
		)
	}
	hasChanges, err := d.repository.hasRangeChanges(ctx, baseOID, headOID)
	if err != nil {
		return err
	}
	if !hasChanges {
		return fmt.Errorf("prepared feature commit has an empty aggregate diff")
	}
	return nil
}

type verifyReport struct {
	Inspection *inspection `json:"inspection"`
	Verified   bool        `json:"verified"`
}

func (d *delivery) verify(
	ctx context.Context,
	receipt *preparationReceipt,
) (*verifyReport, error) {
	report, err := d.inspect(ctx)
	if err != nil {
		return nil, err
	}
	if receipt != nil {
		if err := d.validateReceiptContext(ctx, *receipt, report); err != nil {
			return nil, fmt.Errorf("preparation receipt refused: %w", err)
		}
		if err := requireCleanPreparedScope(report.Status, receipt.Scope); err != nil {
			return nil, err
		}
		if err := d.repository.requireDefaultIndexFlags(
			ctx,
			receipt.Scope.AuthorizedPaths,
		); err != nil {
			return nil, fmt.Errorf("verification index flag gate: %w", err)
		}
	}
	if err := ensureNoRefusals(report); err != nil {
		return nil, err
	}
	if len(report.Status.Staged) != 0 {
		return nil, fmt.Errorf("final index is not clean")
	}
	if err := d.repository.requireIndexTree(
		ctx,
		report.LocalTreeOID,
	); err != nil {
		return nil, fmt.Errorf("final verification index gate: %w", err)
	}
	if !report.BaseIsAncestor {
		return nil, fmt.Errorf("final feature range is not one rebased non-merge commit")
	}
	if err := d.requireSingleCommit(
		ctx,
		report.BaseOID,
		report.LocalHeadOID,
	); err != nil {
		return nil, err
	}
	if err := d.repository.rangeDiffCheck(
		ctx,
		report.BaseOID,
		report.LocalHeadOID,
	); err != nil {
		return nil, err
	}
	if err := d.repository.verifyRequiredSignature(
		ctx,
		report.LocalHeadOID,
	); err != nil {
		return nil, err
	}
	if report.RemoteHeadOID == "" ||
		report.RemoteHeadOID != report.LocalHeadOID {
		return nil, fmt.Errorf("local HEAD does not equal the fetched remote feature ref")
	}
	if report.PullRequest == nil {
		return nil, fmt.Errorf("no exact open pull request exists")
	}
	if report.PullRequest.HeadRefOID != report.LocalHeadOID {
		return nil, fmt.Errorf("pull request head does not equal local HEAD")
	}
	projection, err := d.repository.projection(ctx, report.LocalHeadOID)
	if err != nil {
		return nil, err
	}
	if receipt != nil {
		state, err := receipt.pullRequestState(
			report.PullRequest,
			report.RemoteHeadOID,
			projection,
		)
		if err != nil {
			return nil, err
		}
		if state != receiptPullRequestDesired {
			return nil, fmt.Errorf(
				"pull request has not reached the receipt's exact desired state",
			)
		}
	}
	if !pullRequestMatchesProjection(
		*report.PullRequest,
		projection,
		report.Base,
		report.Branch,
	) {
		return nil, fmt.Errorf("pull request does not equal the commit projection")
	}
	commitBody, err := d.repository.commitBody(ctx, report.LocalHeadOID)
	if err != nil {
		return nil, err
	}
	if !hasFinalLine(commitBody, commitDisclaimer) ||
		!hasFinalLine(report.PullRequest.Body, pullRequestDisclaimer) {
		return nil, fmt.Errorf("commit or pull request has the wrong final disclaimer")
	}
	if err := d.repository.requireBranchHead(
		ctx,
		report.Branch,
		report.LocalHeadOID,
	); err != nil {
		return nil, err
	}
	currentPullRequest, err := d.currentPullRequestMatchingInspection(
		ctx,
		report,
	)
	if err != nil {
		return nil, err
	}
	report.PullRequest = currentPullRequest
	finalStatus, err := d.requireCandidateBoundary(
		ctx,
		receipt,
		report,
		"final verification",
	)
	if err != nil {
		return nil, err
	}
	report.Status = finalStatus
	return &verifyReport{Inspection: report, Verified: true}, nil
}

func normalizeText(value string) string {
	value = strings.ReplaceAll(value, "\r\n", "\n")
	value = strings.ReplaceAll(value, "\r", "\n")
	return strings.TrimRight(value, "\n")
}

func hasFinalLine(value string, line string) bool {
	normalized := normalizeText(value)
	parts := strings.Split(normalized, "\n")
	return len(parts) != 0 && parts[len(parts)-1] == line
}

func withCommitDisclaimer(message string) (string, error) {
	if !utf8.ValidString(message) {
		return "", fmt.Errorf("commit message is not valid UTF-8")
	}
	normalized := normalizeText(message)
	if normalized == "" {
		return "", fmt.Errorf("commit message is empty")
	}
	lines := strings.Split(normalized, "\n")
	if strings.TrimSpace(lines[0]) == "" {
		return "", fmt.Errorf("commit subject is empty")
	}
	last := lines[len(lines)-1]
	if strings.HasPrefix(last, "LLM-disclaimer:") && last != commitDisclaimer {
		return "", fmt.Errorf("commit message ends with the wrong disclaimer")
	}
	if last != commitDisclaimer {
		normalized += "\n\n" + commitDisclaimer
	}
	return normalized + "\n", nil
}

func pullRequestBody(commitBody string) (string, error) {
	if !utf8.ValidString(commitBody) {
		return "", fmt.Errorf("commit body is not valid UTF-8")
	}
	normalized := normalizeText(commitBody)
	if !hasFinalLine(normalized, commitDisclaimer) {
		return "", fmt.Errorf("commit body does not end with the commit disclaimer")
	}
	lines := strings.Split(normalized, "\n")
	lines[len(lines)-1] = pullRequestDisclaimer
	return strings.Join(lines, "\n") + "\n", nil
}
