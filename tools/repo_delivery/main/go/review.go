func newReviewReplyCommand(
	ctx context.Context,
	config *deliveryConfig,
	getenv func(string) string,
	stdout io.Writer,
	runner commandRunner,
) *cobra.Command {
	options := &reviewReplyOptions{}
	command := &cobra.Command{
		Use:   "reply",
		Short: "Reply to an unchanged unresolved review thread",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			delivery, err := deliveryFromConfig(ctx, config, getenv, runner)
			if err != nil {
				return err
			}
			// Validate the destination before causing an external mutation. The
			// atomic installation is repeated afterward in case local state races.
			receiptPath, err := delivery.receiptPath(
				ctx,
				options.ReplyReceiptFile,
				false,
			)
			if err != nil {
				return fmt.Errorf("validate review reply receipt path: %w", err)
			}
			if err := delivery.requireSameReviewTaskDirectory(
				options.BodyFile,
				receiptPath,
			); err != nil {
				return err
			}
			body, err := delivery.readReviewBody(ctx, options.BodyFile)
			if err != nil {
				return fmt.Errorf("read review body: %w", err)
			}
			body, err = withCommentDisclaimer(body)
			if err != nil {
				return err
			}
			inspection, err := delivery.replyToReviewThread(
				ctx,
				options.reviewTargetOptions,
				reviewThreadExpectation{
					ThreadID:              options.ThreadID,
					ExpectedLastCommentID: options.ExpectedLastCommentID,
					ExpectedDigest:        options.ExpectedThreadDigest,
				},
				body,
			)
			if err != nil {
				return err
			}
			receipt, err := delivery.newReviewReplyReceipt(
				ctx,
				options.reviewTargetOptions,
				options.ThreadID,
				options.ExpectedThreadDigest,
				body,
				inspection,
			)
			if err != nil {
				return fmt.Errorf(
					"reply succeeded but its receipt could not be constructed; do not resolve the thread: %w",
					err,
				)
			}
			if err := delivery.writeReviewReplyReceipt(
				ctx,
				options.ReplyReceiptFile,
				receipt,
			); err != nil {
				return fmt.Errorf(
					"reply succeeded but its receipt could not be installed; do not retry the reply or resolve the thread: %w",
					err,
				)
			}
			return writeJSON(stdout, inspection)
		},
	}
	addReviewTargetFlags(command, &options.reviewTargetOptions)
	flags := command.Flags()
	flags.StringVar(&options.ThreadID, "thread-id", "", "exact review thread node ID")
	flags.StringVar(
		&options.ExpectedLastCommentID,
		"expected-last-comment-id",
		"",
		"exact last comment node ID observed by review inspect",
	)
	flags.StringVar(
		&options.ExpectedThreadDigest,
		"expected-thread-digest",
		"",
		"exact thread digest observed by review inspect",
	)
	flags.StringVar(
		&options.BodyFile,
		"body-file",
		"",
		"ignored review reply body under out/<task>/",
	)
	flags.StringVar(
		&options.ReplyReceiptFile,
		"reply-receipt-file",
		"",
		"ignored output receipt under out/<task>/ required for resolution",
	)
	_ = command.MarkFlagRequired("thread-id")
	_ = command.MarkFlagRequired("expected-last-comment-id")
	_ = command.MarkFlagRequired("expected-thread-digest")
	_ = command.MarkFlagRequired("body-file")
	_ = command.MarkFlagRequired("reply-receipt-file")
	return command
}

func (d *delivery) requireSameReviewTaskDirectory(
	bodyFile string,
	receiptPath string,
) error {
	taskForPath := func(value string) (string, error) {
		absolute := value
		if !filepath.IsAbs(absolute) {
			absolute = filepath.Join(d.repository.directory, absolute)
		}
		absolute = filepath.Clean(absolute)
		relative, err := filepath.Rel(d.repository.directory, absolute)
		if err != nil {
			return "", err
		}
		parts := strings.Split(filepath.ToSlash(relative), "/")
		if len(parts) < 3 || parts[0] != "out" || parts[1] == "" ||
			parts[1] == "." || parts[1] == ".." {
			return "", fmt.Errorf("path is not under out/<task>/")
		}
		return parts[1], nil
	}
	bodyTask, err := taskForPath(bodyFile)
	if err != nil {
		return fmt.Errorf("locate review body task directory: %w", err)
	}
	receiptTask, err := taskForPath(receiptPath)
	if err != nil {
		return fmt.Errorf("locate review reply receipt task directory: %w", err)
	}
	if bodyTask != receiptTask {
		return fmt.Errorf(
			"--body-file and --reply-receipt-file must share the same out/<task>/ directory",
		)
	}
	return nil
}

