// reviewReplyReceipt is a local consistency record proving that this tool
// observed its own reply before a later resolution. It deliberately contains
// no comment body or remote URL and is not an unforgeable authorization token.
type reviewReplyReceipt struct {
	Schema                string           `json:"schema"`
	IssuedAt              string           `json:"issued_at"`
	ExpiresAt             string           `json:"expires_at"`
	RepositoryFingerprint string           `json:"repository_fingerprint"`
	RemoteRepository      remoteRepository `json:"remote_repository"`
	Forge                 string           `json:"forge"`
	PullRequestID         string           `json:"pull_request_id"`
	PullRequestNumber     int              `json:"pull_request_number"`
	PullRequestDigest     string           `json:"pull_request_digest"`
	PullRequestUpdatedAt  string           `json:"pull_request_updated_at"`
	ReviewInventoryDigest string           `json:"review_inventory_digest"`
	HeadOID               string           `json:"head_oid"`
	ThreadID              string           `json:"thread_id"`
	PriorThreadDigest     string           `json:"prior_thread_digest"`
	ReplyCommentID        string           `json:"reply_comment_id"`
	ReplyBodyDigest       string           `json:"reply_body_digest"`
	ResultThreadDigest    string           `json:"result_thread_digest"`
}

type reviewReplyReceiptClockKey struct{}

func withReviewReplyReceiptClock(
	ctx context.Context,
	clock func() time.Time,
) context.Context {
	return context.WithValue(ctx, reviewReplyReceiptClockKey{}, clock)
}

func reviewReplyReceiptNow(ctx context.Context) time.Time {
	if clock, ok := ctx.Value(reviewReplyReceiptClockKey{}).(func() time.Time); ok &&
		clock != nil {
		return clock()
	}
	return time.Now()
}

