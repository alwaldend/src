func (d *delivery) resolveReviewThread(
	ctx context.Context,
	options reviewTargetOptions,
	expectation reviewThreadExpectation,
	replyReceiptFile string,
) (*reviewInspection, error) {
	pullRequest, capability, err := d.expectedReviewTarget(ctx, options)
	if err != nil {
		return nil, err
	}
	if err := validateThreadExpectation(expectation); err != nil {
		return nil, err
	}
	receipt, err := d.readReviewReplyReceipt(ctx, replyReceiptFile)
	if err != nil {
		return nil, fmt.Errorf("read review reply receipt: %w", err)
	}
	if err := d.validateReviewReplyReceiptContext(
		ctx,
		receipt,
		options,
		*pullRequest,
		expectation,
	); err != nil {
		return nil, err
	}
	expectation.RequiredReplyBodyDigest = receipt.ReplyBodyDigest
	expectation.RequiredInventoryDigest = receipt.ReviewInventoryDigest
	expectation.AuthorityExpiresAt = receipt.ExpiresAt
	consumed, err := d.consumeReviewReplyReceipt(
		ctx,
		replyReceiptFile,
		receipt,
	)
	if err != nil {
		return nil, fmt.Errorf("consume review reply receipt: %w", err)
	}
	if err := receipt.validateAuthorityAt(reviewReplyReceiptNow(ctx)); err != nil {
		cleanupErr := consumed.cleanup()
		return nil, errors.Join(err, cleanupErr)
	}
	inspection, resolveErr := capability.ResolveReviewThread(
		ctx,
		d.remoteRepository,
		*pullRequest,
		expectation,
	)
	cleanupErr := consumed.cleanup()
	if resolveErr != nil {
		retryErr := fmt.Errorf(
			"review reply receipt was consumed before the resolution attempt; " +
				"post a fresh reply before another attempt",
		)
		if cleanupErr != nil {
			return nil, errors.Join(resolveErr, retryErr, cleanupErr)
		}
		return nil, errors.Join(resolveErr, retryErr)
	}
	if cleanupErr != nil {
		return nil, fmt.Errorf(
			"review thread resolution succeeded, but cleaning the consumed "+
				"reply receipt failed: %w",
			cleanupErr,
		)
	}
	return inspection, nil
}

