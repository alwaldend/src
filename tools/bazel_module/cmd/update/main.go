package main

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"os/signal"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"git.alwaldend.com/alwaldend/src/tools/go/pkg/flagcompat"
	"github.com/bazelbuild/rules_go/go/runfiles"
	"github.com/spf13/cobra"
)

// header declares the root module before the generated sequence of include statements.
const header = `# Generated by //tools/bazel_module:update. Do not edit.
module(
    name = "com_alwaldend_src",
    version = "0.0.0",
    bazel_compatibility = [">=9.3.1"],
)
`

// maxManifestBytes bounds the path listing, ignore rules, and root module read into memory.
// The path listing includes only module declarations and workspace boundary markers.
const maxManifestBytes = 16 << 20

// main configures the command and reports update failures to Bazel.
func main() {
	var git string
	var check bool
	command := &cobra.Command{
		Use:           "update",
		Short:         "Generate the root Bazel module include list",
		Args:          cobra.NoArgs,
		SilenceUsage:  true,
		SilenceErrors: true,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if err := update(cmd.Context(), os.Getenv("BUILD_WORKSPACE_DIRECTORY"), git, check); err != nil {
				return fmt.Errorf("update root module: %w", err)
			}
			return nil
		},
	}
	command.Flags().StringVar(&git, "git", "", "Git executable runfile")
	command.Flags().BoolVar(&check, "check", false, "Check without writing")
	if err := command.MarkFlagRequired("git"); err != nil {
		fmt.Fprintf(os.Stderr, "configure Git flag: %v\n", err)
		os.Exit(1)
	}
	flagcompat.SetArgs(command, os.Args[1:])
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt)
	err := command.ExecuteContext(ctx)
	stop()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// update checks or replaces MODULE.bazel from the current worktree's regular module files.
func update(ctx context.Context, root, git string, check bool) error {
	if root == "" {
		return fmt.Errorf("run with bazel run //tools/bazel_module:update")
	}
	gitPath, err := runfiles.Rlocation(git)
	if err != nil {
		return fmt.Errorf("resolve Git runfile %q: %w", git, err)
	}
	cmd := exec.CommandContext(ctx, gitPath, "--git-dir", filepath.Join(root, ".git"), "-C", root, "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--",
		":(glob)**/MODULE.bazel", ":(glob)**/include.MODULE.bazel", ":(glob)**/WORKSPACE", ":(glob)**/WORKSPACE.bazel")
	cmd.Stderr = os.Stderr
	stdout, err := cmd.StdoutPipe()
	if err != nil {
		return fmt.Errorf("open Git file listing: %w", err)
	}
	if err := cmd.Start(); err != nil {
		return fmt.Errorf("start module discovery: %w", err)
	}
	output, readErr := readManifest(stdout)
	err = errors.Join(readErr, stdout.Close(), cmd.Wait())
	if err != nil {
		return fmt.Errorf("discover module files: %w", err)
	}
	files := make([]string, 0, bytes.Count(output, []byte{0}))
	for name := range strings.SplitSeq(string(output), "\x00") {
		if name == "" {
			continue
		}
		info, err := os.Lstat(filepath.Join(root, filepath.FromSlash(name)))
		if os.IsNotExist(err) {
			continue // Git still lists unstaged deletions.
		}
		if err != nil {
			return fmt.Errorf("inspect workspace file %q: %w", name, err)
		}
		if info.Mode().IsRegular() {
			files = append(files, name)
		}
	}
	ignored, err := readManifestFile(filepath.Join(root, ".bazelignore"))
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("load workspace exclusions: %w", err)
	}
	want := generate(files, string(ignored))
	filename := filepath.Join(root, "MODULE.bazel")
	got, err := readManifestFile(filename)
	if err != nil {
		return fmt.Errorf("read existing module: %w", err)
	}
	if bytes.Equal(got, want) {
		return nil
	}
	if check {
		return fmt.Errorf("MODULE.bazel is stale; run bazel run //tools/bazel_module:update")
	}
	if len(want) > maxManifestBytes {
		return fmt.Errorf("generated %q exceeds %d bytes", filename, maxManifestBytes)
	}
	if err := os.WriteFile(filename, want, 0o644); err != nil {
		return fmt.Errorf("write root module %q: %w", filename, err)
	}
	return nil
}

// readManifestFile opens and reads a workspace metadata file within the discovery limit.
func readManifestFile(path string) ([]byte, error) {
	file, err := os.Open(path)
	if err != nil {
		return nil, fmt.Errorf("open %q: %w", path, err)
	}
	data, readErr := readManifest(file)
	if err := errors.Join(readErr, file.Close()); err != nil {
		return nil, fmt.Errorf("read %q: %w", path, err)
	}
	return data, nil
}

// readManifest rejects oversized metadata before passing it to the generator.
func readManifest(reader io.Reader) ([]byte, error) {
	data, err := io.ReadAll(io.LimitReader(reader, maxManifestBytes+1))
	if err != nil {
		return nil, fmt.Errorf("read module metadata: %w", err)
	}
	if len(data) > maxManifestBytes {
		return nil, fmt.Errorf("module metadata exceeds %d bytes", maxManifestBytes)
	}
	return data, nil
}

// generate renders sorted includes from regular files outside ignored and independent workspaces.
func generate(files []string, bazelignore string) []byte {
	boundaries := make(map[string]bool)
	for _, file := range files {
		switch path.Base(file) {
		case "MODULE.bazel", "WORKSPACE", "WORKSPACE.bazel":
			if dir := path.Dir(file); dir != "." {
				boundaries[dir] = true
			}
		}
	}
	for line := range strings.SplitSeq(bazelignore, "\n") {
		line = strings.TrimSpace(strings.SplitN(line, "#", 2)[0])
		if line != "" {
			boundaries[strings.TrimSuffix(line, "/")] = true
		}
	}
	owners := make(map[string]bool)
	for _, file := range files {
		if path.Base(file) != "include.MODULE.bazel" {
			continue
		}
		excluded := false
		for dir := path.Dir(file); dir != "."; dir = path.Dir(dir) {
			if boundaries[dir] {
				excluded = true
				break
			}
		}
		if !excluded {
			owners[path.Dir(file)] = true
		}
	}
	sorted := make([]string, 0, len(owners))
	for owner := range owners {
		sorted = append(sorted, owner)
	}
	// Preserve the existing dependency/toolchain precedence between trees.
	group := func(owner string) int {
		switch strings.SplitN(owner, "/", 2)[0] {
		case "third_party":
			return 0
		case "tools":
			return 1
		case "projects":
			return 2
		default:
			return 3
		}
	}
	sort.Slice(sorted, func(i, j int) bool {
		if a, b := group(sorted[i]), group(sorted[j]); a != b {
			return a < b
		}
		return sorted[i] < sorted[j]
	})
	var result bytes.Buffer
	result.WriteString(header)
	for _, owner := range sorted {
		if owner == "." {
			owner = ""
		}
		fmt.Fprintf(&result, "\ninclude(\"//%s:include.MODULE.bazel\")", owner)
	}
	result.WriteByte('\n')
	return result.Bytes()
}
