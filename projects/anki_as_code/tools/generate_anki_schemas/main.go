package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
)

// main runs the explicit descriptor-to-imports generation command.
func main() {
	var descriptors, output string
	command := &cobra.Command{
		Use: "generate_anki_schemas", Args: cobra.NoArgs, SilenceUsage: true, SilenceErrors: true,
		RunE: func(_ *cobra.Command, _ []string) error {
			if err := generate(descriptors, output); err != nil {
				return fmt.Errorf("generate Anki schema imports: %w", err)
			}
			return nil
		},
	}
	command.Flags().StringVar(&descriptors, "descriptors", "", "Pinned Anki FileDescriptorSet file")
	command.Flags().StringVar(&output, "output", "", "Generated Go output file")
	if err := command.Execute(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// generate writes deterministic registration imports after validating descriptor input.
func generate(descriptors, output string) error {
	if descriptors == "" || output == "" {
		return fmt.Errorf("descriptors and output paths are required")
	}
	data, err := os.ReadFile(descriptors)
	if err != nil {
		return fmt.Errorf("read descriptor set %q: %w", descriptors, err)
	}
	var files descriptorpb.FileDescriptorSet
	if err := proto.Unmarshal(data, &files); err != nil {
		return fmt.Errorf("decode descriptor set %q: %w", descriptors, err)
	}
	imports := map[string]struct{}{}
	for _, file := range files.GetFile() {
		name, ok := strings.CutPrefix(file.GetName(), "anki/")
		if !ok {
			continue
		}
		name, ok = strings.CutSuffix(name, ".proto")
		if !ok || name == "" || strings.ContainsAny(name, "/\\") {
			return fmt.Errorf("unsupported Anki schema path %q", file.GetName())
		}
		imports["github.com/ankitects/anki/proto/anki/"+name] = struct{}{}
	}
	if len(imports) == 0 {
		return fmt.Errorf("descriptor set %q contains no Anki schemas", descriptors)
	}
	paths := make([]string, 0, len(imports))
	for path := range imports {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by generate_anki_schemas; DO NOT EDIT.\n\npackage rpc\n\nimport (")
	for _, path := range paths {
		fmt.Fprintf(&source, "\t_ %q\n", path)
	}
	fmt.Fprintln(&source, ")")
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return fmt.Errorf("format schema imports: %w", err)
	}
	if err := os.WriteFile(output, formatted, 0o644); err != nil {
		return fmt.Errorf("write schema imports %q: %w", output, err)
	}
	return nil
}
