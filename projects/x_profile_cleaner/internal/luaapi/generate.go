package luaapi

import (
	"fmt"
	"sort"
	"strings"

	"git.alwaldend.com/alwaldend/src/projects/x_profile_cleaner/api/archivepb"
	"git.alwaldend.com/alwaldend/src/projects/x_profile_cleaner/api/workerpb"
	"google.golang.org/protobuf/reflect/protoreflect"
)

// OperationFields returns the ordered schema fields exposed as plan methods.
func OperationFields() protoreflect.FieldDescriptors {
	return (&workerpb.Operation{}).ProtoReflect().Descriptor().Oneofs().Get(0).Fields()
}

// OperationArgument selects a positional required string or target identifier.
// Remaining fields form an options table; presence-sensitive payloads stay tables.
// Runtime bindings and generated editor signatures share this exact rule.
func OperationArgument(operation protoreflect.FieldDescriptor) protoreflect.FieldDescriptor {
	message := operation.Message()
	if message == nil || message.Fields().Len() == 0 {
		return nil
	}
	field := message.Fields().Get(0)
	if field.Kind() == protoreflect.StringKind && !field.HasPresence() && !field.IsList() && (message.Fields().Len() == 1 || strings.HasSuffix(string(field.Name()), "_id")) {
		return field
	}
	return nil
}

// Generate renders archive types and plan methods from their protobuf descriptors.
// It emits only argument types used by the API, without returned-plan declarations.
func Generate() ([]byte, error) {
	// definition identifies one complete or filtered protobuf argument class.
	type definition struct {
		// message owns this class's fields and nested types.
		message protoreflect.MessageDescriptor
		// omit is the positional argument excluded from an options class.
		omit protoreflect.FieldDescriptor
	}
	classes := map[string]definition{}
	symbols := map[string]protoreflect.FullName{}
	enums := map[string]protoreflect.EnumDescriptor{}
	var collect func(string, protoreflect.MessageDescriptor, protoreflect.FieldDescriptor) error
	collect = func(name string, message protoreflect.MessageDescriptor, omit protoreflect.FieldDescriptor) error {
		if previous, exists := symbols[name]; exists && previous != message.FullName() {
			return fmt.Errorf("duplicate Lua type name %s", name)
		}
		if _, exists := classes[name]; exists {
			return nil
		}
		symbols[name] = message.FullName()
		classes[name] = definition{message: message, omit: omit}
		for index := 0; index < message.Fields().Len(); index++ {
			field := message.Fields().Get(index)
			if field == omit {
				continue
			}
			if enum := field.Enum(); enum != nil {
				symbol := luaEnumName(enum)
				if previous, exists := symbols[symbol]; exists && previous != enum.FullName() {
					return fmt.Errorf("duplicate Lua enum name %s", symbol)
				}
				symbols[symbol], enums[symbol] = enum.FullName(), enum
			}
			if nested := field.Message(); nested != nil {
				if err := collect(luaName(nested), nested, nil); err != nil {
					return fmt.Errorf("collect nested argument type: %w", err)
				}
			}
		}
		return nil
	}
	for _, message := range []protoreflect.MessageDescriptor{(&archivepb.Account{}).ProtoReflect().Descriptor(), (&archivepb.Following{}).ProtoReflect().Descriptor(), (&archivepb.Like{}).ProtoReflect().Descriptor(), (&archivepb.Tweet{}).ProtoReflect().Descriptor()} {
		if err := collect(luaName(message), message, nil); err != nil {
			return nil, fmt.Errorf("collect archive types: %w", err)
		}
	}
	operations := OperationFields()
	for index := 0; index < operations.Len(); index++ {
		operation := operations.Get(index)
		message := operation.Message()
		if message == nil {
			return nil, fmt.Errorf("operation payload must be a message")
		}
		argument := OperationArgument(operation)
		name := luaName(message)
		if argument != nil {
			if message.Fields().Len() == 1 {
				continue
			}
			name += "Options"
		}
		if err := collect(name, message, argument); err != nil {
			return nil, fmt.Errorf("collect operation arguments: %w", err)
		}
	}
	var output strings.Builder
	output.WriteString("---@meta\n\n-- Code generated by cmd/generate_lua_api from api/workerpb/worker.proto and api/archivepb/archive.proto. DO NOT EDIT.\n-- Editor-only archive records and plan methods; runtime validates values and bounds.\n--# selene: allow(unused_variable, unscoped_variables)\n\n")
	orderedEnums := make([]string, 0, len(enums))
	for name := range enums {
		orderedEnums = append(orderedEnums, name)
	}
	sort.Strings(orderedEnums)
	for _, name := range orderedEnums {
		enum := enums[name]
		output.WriteString("---@alias " + name + "\n")
		for index := 0; index < enum.Values().Len(); index++ {
			output.WriteString(fmt.Sprintf("---| %q\n", enum.Values().Get(index).Name()))
		}
		output.WriteString("\n")
	}
	ordered := make([]string, 0, len(classes))
	for name := range classes {
		ordered = append(ordered, name)
	}
	sort.Strings(ordered)
	for _, name := range ordered {
		value := classes[name]
		if err := writeClass(&output, name, value.message, value.omit); err != nil {
			return nil, fmt.Errorf("write Lua argument class: %w", err)
		}
	}
	output.WriteString("-- Calls collect operations; they never execute X requests.\nplan = {}\n\n")
	for index := 0; index < operations.Len(); index++ {
		operation := operations.Get(index)
		message := operation.Message()
		argument := OperationArgument(operation)
		parameters := "value"
		if argument == nil {
			output.WriteString("---@param value " + luaName(message) + "\n")
		} else {
			parameters = string(argument.Name())
			kind, err := fieldType(argument)
			if err != nil {
				return nil, fmt.Errorf("write positional argument: %w", err)
			}
			output.WriteString("---@param " + parameters + " " + kind + "\n")
			if message.Fields().Len() > 1 {
				output.WriteString("---@param options? " + luaName(message) + "Options\n")
				parameters += ", options"
			}
		}
		output.WriteString("function plan." + string(operation.Name()) + "(" + parameters + ") end\n\n")
	}
	return []byte(strings.TrimRight(output.String(), "\n") + "\n"), nil
}

// luaName qualifies schema names in the project editor namespace.
func luaName(message protoreflect.MessageDescriptor) string {
	if message.ParentFile().Package() == "x_profile_cleaner.archive" {
		return "Archive" + string(message.Name())
	}
	return "Worker" + string(message.Name())
}

// luaEnumName qualifies schema enums alongside their owning message classes.
func luaEnumName(value protoreflect.EnumDescriptor) string {
	if value.ParentFile().Package() == "x_profile_cleaner.archive" {
		return "Archive" + string(value.Name())
	}
	return "Worker" + string(value.Name())
}

// writeClass emits the schema fields used by one archive record or argument table.
func writeClass(output *strings.Builder, name string, message protoreflect.MessageDescriptor, omit protoreflect.FieldDescriptor) error {
	output.WriteString("---@class (exact) " + name + "\n")
	for index := 0; index < message.Fields().Len(); index++ {
		field := message.Fields().Get(index)
		if field == omit {
			continue
		}
		value, err := fieldType(field)
		if err != nil {
			return fmt.Errorf("render field type: %w", err)
		}
		optional := ""
		if field.Kind() == protoreflect.BoolKind || (message.ParentFile().Package() == "x_profile_cleaner.archive" && field.HasPresence() && field.Message() == nil) {
			optional = "?"
		}
		output.WriteString("---@field " + string(field.Name()) + optional + " " + value + "\n")
	}
	output.WriteString("local " + name + " = {}\n\n")
	return nil
}

// fieldType translates the scalar/message kinds supported by the Lua runtime.
func fieldType(field protoreflect.FieldDescriptor) (string, error) {
	if field.IsMap() {
		return "", fmt.Errorf("map fields are unsupported")
	}
	value := ""
	switch field.Kind() {
	case protoreflect.StringKind:
		value = "string"
	case protoreflect.BoolKind:
		value = "boolean"
	case protoreflect.Int32Kind, protoreflect.Int64Kind:
		value = "integer"
		if field.Kind() == protoreflect.Int64Kind && field.ParentFile().Package() == "x_profile_cleaner.archive" {
			value = "integer|string"
		}
	case protoreflect.EnumKind:
		value = luaEnumName(field.Enum())
	case protoreflect.MessageKind:
		value = luaName(field.Message())
	default:
		return "", fmt.Errorf("unsupported Lua protobuf kind %s", field.Kind())
	}
	if field.IsList() {
		if strings.Contains(value, "|") {
			value = "(" + value + ")"
		}
		value += "[]"
	}
	return value, nil
}
