package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"

	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
)

// generate validates upstream descriptors and emits one registration per service/method.
func generate(input, output string) error {
	data, err := os.ReadFile(input)
	if err != nil {
		return fmt.Errorf("read Anki descriptors: %w", err)
	}
	set := new(descriptorpb.FileDescriptorSet)
	if err := proto.Unmarshal(data, set); err != nil {
		return fmt.Errorf("parse Anki descriptors: %w", err)
	}
	files, err := protodesc.NewFiles(set)
	if err != nil {
		return fmt.Errorf("resolve Anki descriptors: %w", err)
	}
	var services []protoreflect.ServiceDescriptor
	files.RangeFiles(func(file protoreflect.FileDescriptor) bool {
		for i := 0; i < file.Services().Len(); i++ {
			services = append(services, file.Services().Get(i))
		}
		return true
	})
	sort.Slice(services, func(i, j int) bool { return services[i].FullName() < services[j].FullName() })
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by generate_anki_cli from upstream Anki protobuf. DO NOT EDIT.")
	fmt.Fprintln(&out, "package cli")
	fmt.Fprintln(&out, `import("github.com/spf13/cobra";"google.golang.org/protobuf/reflect/protoregistry")`)
	fmt.Fprintf(&out, "const schemaData = %q\n", string(data))
	fmt.Fprintln(&out, "func addGenerated(root *cobra.Command, options *options, files *protoregistry.Files) error {")
	methods := 0
	for _, service := range services {
		if service.Methods().Len() == 0 {
			continue
		}
		fmt.Fprintf(&out, "if err:=options.addService(root,files,%q,[]string{", service.FullName())
		for i := 0; i < service.Methods().Len(); i++ {
			method := service.Methods().Get(i)
			if method.IsStreamingClient() || method.IsStreamingServer() {
				return fmt.Errorf("streaming RPC %s is unsupported", method.FullName())
			}
			fmt.Fprintf(&out, "%q,", method.Name())
			methods++
		}
		fmt.Fprintln(&out, "});err!=nil{return err}")
	}
	if methods == 0 {
		return fmt.Errorf("Anki descriptor set contains no unary RPCs")
	}
	fmt.Fprintln(&out, "return nil\n}")
	source, err := format.Source(out.Bytes())
	if err != nil {
		return fmt.Errorf("format generated commands: %w", err)
	}
	if err := os.WriteFile(output, source, 0o644); err != nil {
		return fmt.Errorf("write generated commands: %w", err)
	}
	return nil
}

// main accepts Bazel-owned descriptor and output paths and reports generation errors.
func main() {
	input := flag.String("descriptor", "", "upstream FileDescriptorSet")
	output := flag.String("output", "", "generated Go output")
	flag.Parse()
	if err := generate(*input, *output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
